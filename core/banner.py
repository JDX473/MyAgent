TAGLINE = "Feidudu —— 你的智能助手"


def banner() -> str:
    """返回纯文本横幅（图腾 + 标题 + 副标题）。"""
    return f"{TIGER_HEAD}\n{TITLE}{TAGLINE}\n"


def print_banner() -> None:
    """打印带颜色的横幅到终端（ANSI，非 TTY 自动降级为纯文本）。"""
    import sys

    def vt(s):
        return s if getattr(sys.stdout, "isatty", lambda: False)() else ""

    dark_orange = "\033[33;1m"  # 亮黄
    cyan = "\033[36m"           # 标题
    dim = "\033[2m"             # 副标题
    reset = "\033[0m"

    print(f"{vt(dark_orange)}{TIGER_HEAD}{vt(reset)}")
    print(f"{vt(cyan)}{TITLE}{vt(reset)}")
    print(f"{vt(dim)}{TAGLINE}{vt(reset)}\n")

